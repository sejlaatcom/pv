/**
 * نسخ مسابقات البنك إلى جهة، مع تجاهل ما سبق نسخه (بمطابقة العنوان).
 * تُنسخ كمسودات ليراجعها المشرف قبل النشر.
 */
function quiz_bank_import(int $entityId, ?int $userId = null): int
{
    $existing = array_column(
        db_all('SELECT title FROM quizzes WHERE entity_id = ?', [$entityId]),
        'title'
    );

    $imported = 0;
    foreach (quiz_bank() as $bankQuiz) {
        if (in_array($bankQuiz['title'], $existing, true)) {
            continue;
        }

        $questions = [];
        foreach ($bankQuiz['questions'] as [$text, $options, $correct]) {
            $questions[] = ['question' => $text, 'options' => $options, 'correct' => $correct];
        }

        quiz_create($entityId, [
            'title'              => $bankQuiz['title'],
            'description'        => $bankQuiz['description'],
            'type'               => $bankQuiz['type'] ?? 'quiz',
            'category'           => $bankQuiz['category'],
            'points_per_correct' => 5,
            'time_limit_minutes' => ($bankQuiz['type'] ?? 'quiz') === 'survey' ? null : 10,
        ], $questions, $userId);

        $imported++;
    }

    return $imported;
}
